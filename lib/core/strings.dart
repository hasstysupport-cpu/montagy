  // ── تنسيقات ──
  static String durationLabel(double seconds) {
    if (seconds.isNaN || seconds.isInfinite || seconds < 0) seconds = 0;
    final int m = seconds ~/ 60;
    final int s = seconds.floor() % 60;
    return '$m:${s.toString().padLeft(2, '0')}';
  }

  static String durationLabelMs(int milliseconds) =>
      durationLabel(milliseconds / 1000.0);

  static String speedLabel(double v) {
    if (v == v.roundToDouble()) return '${v.toInt()}x';
    return '${v.toStringAsFixed(2).replaceAll(RegExp(r'0+$'), '').replaceAll(RegExp(r'\.$'), '')}x';
  }
